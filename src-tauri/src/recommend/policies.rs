/// The app to clear this rule's storage in, when DiskPilot leaves it to the app.
pub fn owner_app(rule_id: &str) -> Option<&'static OwnerApp> {
    OWNER_APPS
        .iter()
        .find(|(id, _)| *id == rule_id)
        .map(|(_, app)| app)
}

