//! Cleanup policies: how each classifier rule translates into a
//! recommendation. Plain data so the reasoning can be reviewed line by line.
//!
//! Size never decides a tier. A rule without a policy produces no
//! recommendation at all.

use crate::model::{CleanupMethod, Tier};

/// Whether a matched location is recommended as a whole or per child folder.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Expand {
    /// One recommendation for the whole location.
    Whole,
    /// One recommendation per direct subfolder (e.g. per app cache).
    Children,
    /// One per subfolder of a fixed child (e.g. `.nvm/versions/node/*`).
    ChildrenOf(&'static str),
}

#[derive(Debug)]
pub struct Policy {
    pub rule_id: &'static str,
    pub tier: Tier,
    /// Methods DiskPilot may perform. Empty: informational only.
    pub methods: &'static [CleanupMethod],
    pub safe_because: &'static str,
    pub risks: &'static str,
    pub proposed_action: &'static str,
    /// A command the user can run themselves. DiskPilot never runs it.
    pub alternative: Option<&'static str>,
    pub expand: Expand,
    /// Ignore items smaller than this.
    pub min_bytes: u64,
    /// Shown in the cleanup preview when this item is included.
    pub before_you_start: Option<&'static str>,
}

